    launcherButton.addEventListener('click', (e) => {
      e.stopPropagation();
      launcher.classList.toggle('open');
    });

    document.addEventListener('click', (e) => {
      if (!launcher.contains(e.target) && !launcherButton.contains(e.target)) {
        launcher.classList.remove('open');
      }
    });
